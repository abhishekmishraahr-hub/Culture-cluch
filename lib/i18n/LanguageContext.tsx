interface LanguageContextType {
  language: string;
  setLanguage: (lang: string) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState("en");

  // Client-side mount hook to load saved language and prevent hydration mismatch
  useEffect(() => {
    const savedLanguage = localStorage.getItem("language") || getCookie("NEXT_LOCALE") || "en";
    if (translations[savedLanguage]) {
      setLanguageState(savedLanguage);
    }
  }, []);

  const setLanguage = (lang: string) => {
    if (translations[lang]) {
      setLanguageState(lang);
      localStorage.setItem("language", lang);
      setCookie("NEXT_LOCALE", lang, 365);
    }
  };

  const t = (key: string): string => {
    const dict = translations[language] || translations.en;
    let lookupKey = key;
    if (key === "admin-dashboard") lookupKey = "adminDashboard";
    if (key === "vendor-dashboard") {
      const vendorLabels: Record<string, string> = {
        en: "Vendor Dashboard",
        hi: "विक्रेता डैशबोर्ड",
        gu: "વિક્રેતા ડેશબોર્ડ",
        pa: "ਵਿਕਰੇਤਾ ਡੈਸ਼ਬੋਰਡ",
        ta: "விற்பனையாளர் டாஷ்போர்டு",
        te: "విక్రేత డాష్ బోర్డ్",
        mr: "विक्रेता डॅशबोर्ड",
        ml: "വെണ്ടർ ഡാഷ്‌ബോർഡ്",
        kn: "ಮಾರಾಟಗಾರರ ಡ್ಯಾಶ್ ಬೋರ್ಡ್",
        bn: "বিক্রেতা ড্যাশবোর্ড",
        or: "ବିକ୍ରେତା ଡ୍ୟାସବୋର୍ଡ",
        as: "বিক্ৰেତା ড্যাশবৰ্ড"
      };
      return vendorLabels[language] || vendorLabels.en;
    }
    return dict[lookupKey] || translations.en[lookupKey] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useTranslation must be used within a LanguageProvider");
  }
  return context;
}

// Utility helper to read cookies client side
function getCookie(name: string): string | null {
  if (typeof document === "undefined") return null;
  const value = `; ${document.cookie}`;
  const parts = value.split(`; ${name}=`);
  if (parts.length === 2) return parts.pop()?.split(";").shift() || null;
  return null;
}

// Utility helper to write cookies client side
function setCookie(name: string, value: string, days: number) {
  if (typeof document === "undefined") return;
  const d = new Date();
  d.setTime(d.getTime() + days * 24 * 60 * 60 * 1000);
  const expires = `expires=${d.toUTCString()}`;
  document.cookie = `${name}=${value};${expires};path=/;SameSite=Lax`;
}
